#!/usr/bin/env python3
"""Extract the REAL CPU verify_tree_greedy kernel implementation from spec.cpp.

Pure stdlib. Fails loudly (exit 2) if the source text drifts from the pinned
shape, so the oracle can never silently execute a stale/handwritten body.
Writes generated/verify_tree_greedy_real.h plus a provenance JSON.
"""
import hashlib
import json
import sys
from pathlib import Path

SRC = Path("python/sglang/kernels/aot/csrc/cpu/spec.cpp")
OUT = Path("g3-t11/generated/verify_tree_greedy_real.h")
PROV = Path("g3-t11/raw/extraction_provenance.json")

# 1-indexed inclusive range pinned by inspection of this commit.
START, END = 47, 92
REQUIRED = [
    "void verify_tree_greedy_kernel_impl(",
    "int64_t last_accept_index = retrive_index[off];",
    "cur = retrive_next_token[off + cur];",
    "cur = retrive_next_sibling[off + cur];",
    "target_predict[last_accept_index]",
    "accept_index[ai_off + num_correct_drafts] = static_cast<int32_t>(draft_idx);",
]


def main() -> int:
    text = SRC.read_text()
    lines = text.splitlines()
    if len(lines) < END:
        print("FATAL: spec.cpp shorter than pinned range", file=sys.stderr)
        return 2
    body = "\n".join(lines[START - 1 : END]) + "\n"
    for req in REQUIRED:
        if req not in body:
            print(f"FATAL: extracted body missing marker: {req}", file=sys.stderr)
            return 2
    if not body.rstrip().endswith("}"):
        print("FATAL: extracted body does not end at a function brace", file=sys.stderr)
        return 2
    OUT.parent.mkdir(parents=True, exist_ok=True)
    PROV.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// AUTO-GENERATED by g3-t11/extract_real_sources.py. Do not edit.\n"
        f"// Verbatim lines {START}-{END} of {SRC}\n"
        + body
    )
    prov = {
        "source": str(SRC),
        "source_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "extracted_lines": [START, END],
        "extracted_sha256": hashlib.sha256(body.encode()).hexdigest(),
        "markers_ok": True,
    }
    PROV.write_text(json.dumps(prov, indent=2) + "\n")
    print(json.dumps(prov))
    return 0


if __name__ == "__main__":
    sys.exit(main())
